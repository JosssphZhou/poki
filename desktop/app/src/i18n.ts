export function progressLine(line: string): string {
  if (lang === "en") return line;
  const fixed = zh[line];
  if (typeof fixed === "string") return fixed;
  for (const [pattern, key] of progressTemplates) {
    const match = pattern.exec(line);
    if (match) return t(key).replace(/\{(\d+)\}/g, (_, index) => {
      const value = match[Number(index) + 1];
      return key.startsWith("The iPhone stopped answering") || key.endsWith("No Beta releases are available. Try again later.") ? t(value) : value;
    });
  }
  return line;
}
