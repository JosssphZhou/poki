function detectSystemLang(): ResolvedLang {
  const prefs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const raw of prefs) {
    const tag = raw.toLowerCase();
    if (tag.startsWith("en")) return "en";
    if (tag.startsWith("zh")) {
      if (tag.includes("hant") || tag.includes("-tw") || tag.includes("-hk") || tag.includes("-mo")) {
        return "zh-Hant";
      }
      return "zh-Hans";
    }
  }
  return "en";
}

function resolveLang(pref: Lang): ResolvedLang {
  return pref === "system" ? detectSystemLang() : pref;
}

const VALID_PREFS = new Set<Lang>(["system", "en", "zh-Hans", "zh-Hant"]);
const stored = localStorage.getItem("lang") as Lang | null;
let pref: Lang = stored && VALID_PREFS.has(stored) ? stored : "system";
const listeners = new Set<() => void>();

function syncDocumentLang() {
  const resolved = resolveLang(pref);
  document.documentElement.dataset.lang = resolved;
  document.documentElement.lang = resolved;
}

syncDocumentLang();
if (typeof window !== "undefined") {
  window.addEventListener("languagechange", () => {
    if (pref === "system") {
      syncDocumentLang();
      listeners.forEach((f) => f());
    }
  });
}

export function setLang(next: Lang) {
  pref = next;
  localStorage.setItem("lang", next);
  syncDocumentLang();
  listeners.forEach((f) => f());
}

export function useLang(): Lang {
  return useSyncExternalStore(
    (f) => {
      listeners.add(f);
      return () => listeners.delete(f);
    },
    () => pref,
  );
}

function activeDict(): Record<string, string> {
  const active = resolveLang(pref);
  if (active === "zh-Hans") return zhHans;
  if (active === "zh-Hant") return zhHant;
  return en;
}

export function t(key: string): string {
  const dict = activeDict();
  return Object.hasOwn(dict, key) ? dict[key] : key;
}

const ERROR_PATTERNS: { pattern: RegExp; key: string; slots: string[]; nestedLast?: boolean }[] = [
  {
    pattern: /^None of the anisette servers answered \(([\s\S]+?)\)\. Check this computer's internet connection, or set another server in Settings\. Last error: ([\s\S]+)$/,
    key: "None of the anisette servers answered ({servers}). Check this computer's internet connection, or set another server in Settings. Last error: {detail}",
    slots: ["{servers}", "{detail}"],
    nestedLast: true,
  },
  {
    pattern: /^The anisette server (\S+) did not answer \(([\s\S]+)\)\. Check the address in Settings, or try again later\.$/,
    key: "The anisette server {url} did not answer ({detail}). Check the address in Settings, or try again later.",
    slots: ["{url}", "{detail}"],
  },
  {
    pattern: /^anisette provisioning(?: failed)?:\s*(\S[\s\S]*)$/i,
    key: "anisette provisioning failed: {detail}",
    slots: ["{detail}"],
  },
  {
    pattern: /^anisette provisioning(?: failed)?:\s*$/i,
    key: "anisette provisioning failed",
    slots: [],
  },
  {
    pattern: /^anisette:\s*(\S[\s\S]*)$/i,
    key: "anisette: {detail}",
    slots: ["{detail}"],
  },
  {
    pattern: /^Cloudflare:\s*(\S[\s\S]*)$/,
    key: "Cloudflare: {detail}",
    slots: ["{detail}"],
  },
];

export function tError(raw: string): string {
  const dict = activeDict();
  if (Object.hasOwn(dict, raw)) return dict[raw];
  for (const { pattern, key, slots, nestedLast } of ERROR_PATTERNS) {
    const match = pattern.exec(raw);
    if (match) {
      let out = Object.hasOwn(dict, key) ? dict[key] : key;
      slots.forEach((slot, i) => {
        const val = match[i + 1] ?? "";
        const replacement = nestedLast && i === slots.length - 1 ? tError(val) : val;
        out = out.replace(slot, () => replacement);
      });
      return out;
    }
  }
  return raw;
}
