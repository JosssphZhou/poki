const listeners = new Set<() => void>();
let lang: Lang = (localStorage.getItem("lang") as Lang) || (navigator.language.toLowerCase().startsWith("zh") ? "zh-Hans" : navigator.language.toLowerCase().startsWith("vi") ? "vi" : "en");
document.documentElement.dataset.lang = lang;
export function setLang(l: Lang) {
  lang = l;
  localStorage.setItem("lang", l);
  document.documentElement.dataset.lang = l;
  listeners.forEach((f) => f());
}
export function useLang(): Lang {
  return useSyncExternalStore((f) => { listeners.add(f); return () => listeners.delete(f); }, () => lang);
}
export function t(key: string): string {
  return lang === "zh-Hans" ? zh[key] ?? key : lang === "vi" ? vi[key] ?? key : key;
}
